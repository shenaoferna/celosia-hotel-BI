-- Granularidad de RESERVA: una habitación reservada por un huésped para una estadía.
-- =====================================================

-- ---------------------- DIMENSIONES ----------------------

CREATE TABLE huesped (
    hd_id_huesped        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    hd_nombre            VARCHAR2(100) NOT NULL,
    hd_tipo_documento    VARCHAR2(3)   NOT NULL,
    hd_documento         VARCHAR2(20)  NOT NULL,
    hd_fecha_nacimiento  DATE,
    hd_email             VARCHAR2(100),
    hd_telefono          VARCHAR2(20)  NOT NULL,
    hd_pais              VARCHAR2(60)  DEFAULT 'Colombia' NOT NULL,
    CONSTRAINT pk_huesped PRIMARY KEY (hd_id_huesped),
    CONSTRAINT uq_huesped_documento UNIQUE (hd_tipo_documento, hd_documento),
    CONSTRAINT uq_huesped_email UNIQUE (hd_email),
    CONSTRAINT ck_huesped_tipo_doc CHECK (hd_tipo_documento IN ('CC','CE','PAS')),
    -- Formato del documento: CC y CE solo números; pasaporte, letras mayúsculas y números
    CONSTRAINT ck_huesped_formato_doc CHECK (
         (hd_tipo_documento = 'CC'  AND REGEXP_LIKE(hd_documento, '^[0-9]{5,10}$'))
      OR (hd_tipo_documento = 'CE'  AND REGEXP_LIKE(hd_documento, '^[0-9]{4,7}$'))
      OR (hd_tipo_documento = 'PAS' AND REGEXP_LIKE(hd_documento, '^[A-Z0-9]{6,12}$'))
    )
);

CREATE TABLE habitacion (
    ha_id_habitacion  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ha_numero         VARCHAR2(5)   NOT NULL,
    ha_tipo           VARCHAR2(20)  NOT NULL,
    ha_capacidad      NUMBER(1)     NOT NULL,
    ha_piso           NUMBER(2)     NOT NULL,
    ha_precio_noche   NUMBER(10,2)  NOT NULL,
    ha_estado         VARCHAR2(20)  DEFAULT 'activa' NOT NULL,
    CONSTRAINT pk_habitacion PRIMARY KEY (ha_id_habitacion),
    CONSTRAINT uq_habitacion_numero UNIQUE (ha_numero),
    CONSTRAINT ck_habitacion_tipo CHECK (ha_tipo IN ('sencilla','doble','suite','familiar')),
    CONSTRAINT ck_habitacion_capacidad CHECK (ha_capacidad BETWEEN 1 AND 6),
    CONSTRAINT ck_habitacion_piso CHECK (ha_piso >= 1),
    CONSTRAINT ck_habitacion_precio CHECK (ha_precio_noche > 0),
    CONSTRAINT ck_habitacion_estado CHECK (ha_estado IN ('activa','mantenimiento'))
);

CREATE TABLE temporada (
    tp_id_temporada  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tp_nombre        VARCHAR2(60)  NOT NULL,
    tp_fecha_inicio  DATE          NOT NULL,
    tp_fecha_fin     DATE          NOT NULL,
    tp_recargo       NUMBER(5,2)   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_temporada PRIMARY KEY (tp_id_temporada),
    CONSTRAINT uq_temporada_nombre UNIQUE (tp_nombre),
    CONSTRAINT ck_temporada_fechas CHECK (tp_fecha_fin > tp_fecha_inicio),
    CONSTRAINT ck_temporada_recargo CHECK (tp_recargo BETWEEN 0 AND 100)
);

-- ---------------------- TABLA DE HECHOS ----------------------

CREATE TABLE reserva (
    re_id_reserva     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    re_id_huesped     NUMBER        NOT NULL,
    re_id_habitacion  NUMBER        NOT NULL,
    re_id_temporada   NUMBER        NOT NULL,
    re_fecha_reserva  DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
    re_fecha_entrada  DATE          NOT NULL,
    re_fecha_salida   DATE          NOT NULL,
    re_noches         NUMBER(3)     NOT NULL,
    re_num_personas   NUMBER(1)     NOT NULL,
    re_valor_total    NUMBER(12,2)  NOT NULL,
    re_estado         VARCHAR2(20)  DEFAULT 'confirmada' NOT NULL,
    re_canal          VARCHAR2(20)  DEFAULT 'directo' NOT NULL,
    re_calificacion   NUMBER(1),
    re_hora_checkin   DATE,
    re_hora_checkout  DATE,
    CONSTRAINT pk_reserva PRIMARY KEY (re_id_reserva),
    CONSTRAINT uq_reserva_hab_entrada UNIQUE (re_id_habitacion, re_fecha_entrada),
    CONSTRAINT ck_reserva_fechas CHECK (re_fecha_salida > re_fecha_entrada),
    CONSTRAINT ck_reserva_fecha_res CHECK (re_fecha_reserva <= re_fecha_entrada),
    CONSTRAINT ck_reserva_noches CHECK (re_noches > 0 AND re_noches = re_fecha_salida - re_fecha_entrada),
    CONSTRAINT ck_reserva_personas CHECK (re_num_personas >= 1),
    CONSTRAINT ck_reserva_valor CHECK (re_valor_total >= 0),
    CONSTRAINT ck_reserva_estado CHECK (re_estado IN ('confirmada','en_curso','cancelada','finalizada')),
    CONSTRAINT ck_reserva_canal CHECK (re_canal IN ('directo','booking','agencia','walk_in')),
    CONSTRAINT ck_reserva_calif CHECK (re_calificacion BETWEEN 1 AND 5),
    CONSTRAINT ck_reserva_calif_estado CHECK (re_calificacion IS NULL OR re_estado = 'finalizada'),
    CONSTRAINT ck_reserva_en_curso CHECK (re_estado <> 'en_curso' OR re_hora_checkin IS NOT NULL),
    CONSTRAINT ck_reserva_finalizada CHECK (re_estado <> 'finalizada' OR re_hora_checkout IS NOT NULL),
    CONSTRAINT ck_reserva_checkin_estado CHECK (re_hora_checkin IS NULL OR re_estado IN ('en_curso','finalizada')),
    CONSTRAINT ck_reserva_checkout CHECK (re_hora_checkout IS NULL OR re_hora_checkout > re_hora_checkin),
    CONSTRAINT fk_reserva_huesped FOREIGN KEY (re_id_huesped) REFERENCES huesped(hd_id_huesped),
    CONSTRAINT fk_reserva_habitacion FOREIGN KEY (re_id_habitacion) REFERENCES habitacion(ha_id_habitacion),
    CONSTRAINT fk_reserva_temporada FOREIGN KEY (re_id_temporada) REFERENCES temporada(tp_id_temporada)
);

-- Ciclo de vida de una reserva:
--   confirmada --(check-in)--> en_curso --(check-out)--> finalizada
--   confirmada --(cancelar)--> cancelada
--
-- Reglas que no pueden ser CHECK (dependen de otra tabla, de otras filas o de la fecha actual)
-- y que valida la aplicación antes de guardar:
--   1. re_num_personas <= ha_capacidad de la habitación.
--   2. La habitación está 'activa' y no tiene otra reserva no cancelada que se cruce en fechas.
--   3. re_id_temporada corresponde a la temporada donde cae re_fecha_entrada.
--   4. re_valor_total = ha_precio_noche * re_noches * (1 + tp_recargo / 100).
--   5. El huésped es mayor de edad al hacer la reserva.
--   6. El check-in solo se registra cuando la estadía ya empezó.
