-- Star schema: guest, room and season (dimensions) + reservation (fact table).
-- Grain of RESERVATION: one room booked by one guest for one stay.
-- Safe to run again: it first drops the 4 tables if they exist, then creates them from scratch.
-- After it, run DML_hotel.sql to load the test data.
-- =====================================================

-- ---------------------- CLEAN START ----------------------
-- Drops the tables in foreign-key order (the fact table first). Skips any table that doesn't exist yet.
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('RESERVATION', 'GUEST', 'ROOM', 'SEASON')
              ORDER BY CASE table_name WHEN 'RESERVATION' THEN 0 ELSE 1 END) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------------------- DIMENSIONS ----------------------

CREATE TABLE guest (
    gu_guest_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    gu_name          VARCHAR2(100) NOT NULL,
    gu_id_type       VARCHAR2(3)   NOT NULL,
    gu_id_number     VARCHAR2(20)  NOT NULL,
    gu_birth_date    DATE,
    gu_email         VARCHAR2(100),
    gu_phone         VARCHAR2(20)  NOT NULL,
    gu_country       VARCHAR2(60)  DEFAULT 'Colombia' NOT NULL,
    CONSTRAINT pk_guest PRIMARY KEY (gu_guest_id),
    CONSTRAINT uq_guest_id_number UNIQUE (gu_id_type, gu_id_number),
    CONSTRAINT uq_guest_email UNIQUE (gu_email),
    -- ID types: CC = Colombian national ID, CE = foreign resident ID, PAS = passport
    CONSTRAINT ck_guest_id_type CHECK (gu_id_type IN ('CC','CE','PAS')),
    -- ID format: CC and CE digits only; passport, uppercase letters and digits
    CONSTRAINT ck_guest_id_format CHECK (
         (gu_id_type = 'CC'  AND REGEXP_LIKE(gu_id_number, '^[0-9]{5,10}$'))
      OR (gu_id_type = 'CE'  AND REGEXP_LIKE(gu_id_number, '^[0-9]{4,7}$'))
      OR (gu_id_type = 'PAS' AND REGEXP_LIKE(gu_id_number, '^[A-Z0-9]{6,12}$'))
    )
);

CREATE TABLE room (
    ro_room_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ro_number        VARCHAR2(5)   NOT NULL,
    ro_type          VARCHAR2(20)  NOT NULL,
    ro_capacity      NUMBER(1)     NOT NULL,
    ro_floor         NUMBER(2)     NOT NULL,
    ro_nightly_rate  NUMBER(10,2)  NOT NULL,
    ro_status        VARCHAR2(20)  DEFAULT 'active' NOT NULL,
    ro_back_in_service DATE,        -- maintenance only: first day the room can be sold again
    CONSTRAINT pk_room PRIMARY KEY (ro_room_id),
    CONSTRAINT uq_room_number UNIQUE (ro_number),
    CONSTRAINT ck_room_type CHECK (ro_type IN ('single','double','suite','family')),
    CONSTRAINT ck_room_capacity CHECK (ro_capacity BETWEEN 1 AND 6),
    CONSTRAINT ck_room_floor CHECK (ro_floor >= 1),
    CONSTRAINT ck_room_rate CHECK (ro_nightly_rate > 0),
    CONSTRAINT ck_room_status CHECK (ro_status IN ('active','maintenance')),
    -- A room in maintenance must say when it's back in service; an active room has no date
    CONSTRAINT ck_room_back_in_service CHECK (
         (ro_status = 'maintenance' AND ro_back_in_service IS NOT NULL)
      OR (ro_status = 'active' AND ro_back_in_service IS NULL))
);

CREATE TABLE season (
    se_season_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    se_name          VARCHAR2(60)  NOT NULL,
    se_start_date    DATE          NOT NULL,
    se_end_date      DATE          NOT NULL,
    se_surcharge     NUMBER(5,2)   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_season PRIMARY KEY (se_season_id),
    CONSTRAINT uq_season_name UNIQUE (se_name),
    CONSTRAINT ck_season_dates CHECK (se_end_date > se_start_date),
    CONSTRAINT ck_season_surcharge CHECK (se_surcharge BETWEEN 0 AND 100)
);

-- ---------------------- FACT TABLE ----------------------

CREATE TABLE reservation (
    re_reservation_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    re_guest_id         NUMBER        NOT NULL,
    re_room_id          NUMBER        NOT NULL,
    re_season_id        NUMBER        NOT NULL,
    re_booking_date     DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
    re_check_in_date    DATE          NOT NULL,
    re_check_out_date   DATE          NOT NULL,
    re_nights           NUMBER(3)     NOT NULL,
    re_adults           NUMBER(1)     NOT NULL,
    re_children         NUMBER(1)     DEFAULT 0 NOT NULL,
    re_guests           NUMBER(1)     GENERATED ALWAYS AS (re_adults + re_children) VIRTUAL,
    re_total_amount     NUMBER(12,2)  NOT NULL,
    re_status           VARCHAR2(20)  DEFAULT 'confirmed' NOT NULL,
    re_channel          VARCHAR2(20)  DEFAULT 'direct' NOT NULL,
    re_rating           NUMBER(1),
    re_check_in_time    DATE,
    re_check_out_time   DATE,
    CONSTRAINT pk_reservation PRIMARY KEY (re_reservation_id),
    CONSTRAINT uq_reservation_room_check_in UNIQUE (re_room_id, re_check_in_date),
    CONSTRAINT ck_reservation_dates CHECK (re_check_out_date > re_check_in_date),
    CONSTRAINT ck_reservation_booking_date CHECK (re_booking_date <= re_check_in_date),
    CONSTRAINT ck_reservation_nights CHECK (re_nights > 0 AND re_nights = re_check_out_date - re_check_in_date),
    CONSTRAINT ck_reservation_adults CHECK (re_adults >= 1),
    CONSTRAINT ck_reservation_children CHECK (re_children >= 0),
    CONSTRAINT ck_reservation_amount CHECK (re_total_amount >= 0),
    CONSTRAINT ck_reservation_status CHECK (re_status IN ('confirmed','in_house','cancelled','checked_out')),
    CONSTRAINT ck_reservation_channel CHECK (re_channel IN ('direct','booking','agency','walk_in')),
    CONSTRAINT ck_reservation_rating CHECK (re_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reservation_rating_status CHECK (re_rating IS NULL OR re_status = 'checked_out'),
    CONSTRAINT ck_reservation_in_house CHECK (re_status <> 'in_house' OR re_check_in_time IS NOT NULL),
    CONSTRAINT ck_reservation_checked_out CHECK (re_status <> 'checked_out' OR re_check_out_time IS NOT NULL),
    CONSTRAINT ck_reservation_check_in_status CHECK (re_check_in_time IS NULL OR re_status IN ('in_house','checked_out')),
    CONSTRAINT ck_reservation_check_out CHECK (re_check_out_time IS NULL OR re_check_out_time > re_check_in_time),
    CONSTRAINT fk_reservation_guest FOREIGN KEY (re_guest_id) REFERENCES guest(gu_guest_id),
    CONSTRAINT fk_reservation_room FOREIGN KEY (re_room_id) REFERENCES room(ro_room_id),
    CONSTRAINT fk_reservation_season FOREIGN KEY (re_season_id) REFERENCES season(se_season_id)
);

-- Reservation life cycle:
--   confirmed --(check-in)--> in_house --(check-out)--> checked_out
--   confirmed --(cancel)--> cancelled
--
-- Rules that can't be CHECK constraints (they depend on another table, other rows or today's date)
-- and that the application validates before saving:
--   1. re_guests (adults + children) <= ro_capacity of the room.
--   2. The room isn't in maintenance on those dates (it can be sold again from ro_back_in_service) and has no other
--      non-cancelled reservation with overlapping dates. Maintenance whose date has passed counts as active.
--   3. re_season_id matches the season that contains re_check_in_date.
--   4. re_total_amount = ro_nightly_rate * re_nights * (1 + se_surcharge / 100).
--   5. The guest is an adult when making the reservation.
--   6. Check-in is only recorded once the stay has started.
--   7. If re_children > 0, the front desk verifies each minor's ID and the document that proves the relationship
--      to the accompanying adult before check-in (Ley 679 de 2001 and Ley 1336 de 2009).
